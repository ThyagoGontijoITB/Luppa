    @numeroTelefone varchar(20),
    @senha varchar(255),
    @idCategoria int,
    @descricaoCategoria varchar(80),
    @pathImagemPerfil varchar(200),
    @emailVerificado bit,
    @dataVerificacaoEmail datetime2;

SELECT
    @nome = u.nome,
    @sobrenome = u.sobrenome,
    @email = u.email,
    @aniversario = u.aniversario,
    @numeroTelefone = u.numeroTelefone,
    @senha = u.senha,
    @idCategoria = u.idCategoria,
    @descricaoCategoria = tu.descricaoCategoria,
    @pathImagemPerfil = u.pathImagemPerfil,
    @emailVerificado = u.emailVerificado,
    @dataVerificacaoEmail = u.dataVerificacaoEmail
FROM dbo.usuario u
JOIN dbo.tipoUsuario tu
  ON tu.idCategoria = u.idCategoria
WHERE u.idUsuario = @IdUsuario;

IF @senha IS NULL OR LEN(@senha) <= 20
    THROW 52005, 'Local user password hash is missing or unexpectedly short.', 1;

DECLARE @out table (
    line_no int IDENTITY(1,1) PRIMARY KEY,
    sql_text nvarchar(max) NOT NULL
);

DECLARE @legal table (
    idAceiteLegal bigint,
    tipoDocumento varchar(30),
    versaoDocumento varchar(30),
    dataAceite datetime2
);

IF OBJECT_ID(N'dbo.aceiteLegalUsuario', N'U') IS NOT NULL
BEGIN
    INSERT INTO @legal (idAceiteLegal, tipoDocumento, versaoDocumento, dataAceite)
    SELECT idAceiteLegal, tipoDocumento, versaoDocumento, dataAceite
    FROM dbo.aceiteLegalUsuario
    WHERE idUsuario = @IdUsuario
    ORDER BY idAceiteLegal;
END;


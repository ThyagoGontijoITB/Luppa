/*
Run this script manually in SSMS against the LOCAL luppaBD database.

It does not modify data. It emits a second script as rows in the result set.
Copy the emitted rows, in line_no order, and run them manually against the
remote db72445 database.

The emitted script contains the existing encrypted password hash from the
local dbo.usuario row so the account password is preserved. Do not paste the
emitted script into chat or logs.
*/

USE [luppaBD];
GO

SET NOCOUNT ON;

IF DB_NAME() <> N'luppaBD'
    THROW 52000, 'Run this export only against the local luppaBD database.', 1;

DECLARE @IdUsuario int = 24;

IF OBJECT_ID(N'dbo.usuario', N'U') IS NULL
    THROW 52001, 'Required table dbo.usuario was not found.', 1;

IF OBJECT_ID(N'dbo.tipoUsuario', N'U') IS NULL
    THROW 52002, 'Required table dbo.tipoUsuario was not found.', 1;

IF NOT EXISTS (SELECT 1 FROM dbo.usuario WHERE idUsuario = @IdUsuario)
    THROW 52003, 'Local user idUsuario=24 was not found.', 1;

IF NOT EXISTS (
    SELECT 1
    FROM dbo.usuario u
    JOIN dbo.tipoUsuario tu
      ON tu.idCategoria = u.idCategoria
    WHERE u.idUsuario = @IdUsuario
)
    THROW 52004, 'Local user idUsuario=24 does not have a valid tipoUsuario role.', 1;

